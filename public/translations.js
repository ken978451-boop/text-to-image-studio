export const translations = Object.fromEntries(
  SUPPORTED_LOCALES.map((locale, localeIndex) => [
    locale,
    Object.fromEntries(
      Object.entries(messages).map(([key, values]) => [key, values[localeIndex]]),
    ),
  ]),
);

export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function translate(locale, key, replacements = {}) {
  const normalizedLocale = normalizeLocale(locale);
  const template = translations[normalizedLocale][key];
  if (typeof template !== "string") {
    throw new Error(`Missing translation: ${normalizedLocale}:${key}`);
  }

  return template.replace(/\{([a-zA-Z0-9]+)\}/g, (match, name) =>
    Object.hasOwn(replacements, name) ? String(replacements[name]) : match,
  );
}

